    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
            // TODO add your handling code here:
            try {
             int cantidadProductos;
    int unidadesVenta = 0;
    double subtotal = 0;

    cantidadProductos = Integer.parseInt(
        JOptionPane.showInputDialog(
            "¿Cuántos productos tendrá la compra?"
        )
    );

    while (cantidadProductos <= 0) {
        cantidadProductos = Integer.parseInt(
            JOptionPane.showInputDialog(
                "Ingrese un número de productos mayor que cero:"
            )
        );
    }

    // Ingresar todos los productos
    for (int i = 1; i <= cantidadProductos; i++) {

        String codigo = JOptionPane.showInputDialog(
            "Producto #" + i + "\nIngrese el código:"
        );

        String nombre = JOptionPane.showInputDialog(
            "Producto #" + i + "\nIngrese el nombre:"
        );

        double precio = Double.parseDouble(
            JOptionPane.showInputDialog(
                "Producto #" + i + "\nIngrese el precio:"
            )
        );

        while (precio <= 0) {
            precio = Double.parseDouble(
                JOptionPane.showInputDialog(
                    "El precio debe ser mayor que cero:"
                )
            );
        }

        int cantidad = Integer.parseInt(
            JOptionPane.showInputDialog(
                "Producto #" + i + "\nIngrese la cantidad:"
            )
        );

        while (cantidad <= 0) {
            cantidad = Integer.parseInt(
                JOptionPane.showInputDialog(
                    "La cantidad debe ser mayor que cero:"
                )
            );
        }

        double subtotalProducto = precio * cantidad;
        subtotal += subtotalProducto;
        unidadesVenta += cantidad;
    }

    // Calcular descuento de toda la compra
    double porcentajeDescuento;

    if (subtotal < 200) {
        porcentajeDescuento = 0;
    } else if (subtotal < 500) {
        porcentajeDescuento = 0.05;
    } else if (subtotal < 1000) {
        porcentajeDescuento = 0.08;
    } else {
        porcentajeDescuento = 0.10;
    }

    double descuento = subtotal * porcentajeDescuento;
    double montoConDescuento = subtotal - descuento;
    double iva = montoConDescuento * 0.12;
    double total = montoConDescuento + iva;

    // Seleccionar forma de pago
    int opcionPago = Integer.parseInt(
        JOptionPane.showInputDialog(
            "Seleccione forma de pago:\n"
            + "1. Efectivo\n"
            + "2. Tarjeta\n"
            + "3. Transferencia"
        )
    );

    String formaPago = "";
    double efectivoRecibido = 0;
    double cambio = 0;

    switch (opcionPago) {

        case 1:
            formaPago = "Efectivo";

            while (efectivoRecibido < total) {
                efectivoRecibido = Double.parseDouble(
                    JOptionPane.showInputDialog(
                        "Total a pagar: Q" + total
                        + "\nIngrese el efectivo recibido:"
                    )
                );

                if (efectivoRecibido < total) {
                    JOptionPane.showMessageDialog(
                        null,
                        "Efectivo insuficiente. Intente nuevamente."
                    );
                }
            }

            cambio = efectivoRecibido - total;
            break;

        case 2:
            formaPago = "Tarjeta";
            break;

        case 3:
            formaPago = "Transferencia";
            break;

        default:
            JOptionPane.showMessageDialog(
                null,
                "Forma de pago no válida. Registre la venta nuevamente."
            );
            return;
    }

    // Actualizar los acumuladores de la caja
    ventasRealizadas++;
    productosVendidos += unidadesVenta;
    totalVendido += total;
    // Actualizar venta mayor y menor
if (ventasRealizadas == 1) {
    ventaMayor = total;
    ventaMenor = total;
} else {
    if (total > ventaMayor) {
        ventaMayor = total;
    }

    if (total < ventaMenor) {
        ventaMenor = total;
    }
}

    switch (opcionPago) {
    case 1:
        ventasEfectivo += total;
        ventasEfectivoCantidad++;
        break;

    case 2:
        ventasTarjeta += total;
        ventasTarjetaCantidad++;
        break;

    case 3:
        ventasTransferencia += total;
        ventasTransferenciaCantidad++;
        break;
}

    // Mostrar resumen de la venta
    String resumen =
        "===== RESUMEN DE VENTA =====\n"
        + "Cantidad de productos diferentes: "
        + cantidadProductos + "\n"
        + "Unidades vendidas: " + unidadesVenta + "\n"
        + "Subtotal: Q" + String.format("%.2f", subtotal) + "\n"
        + "Descuento: Q" + String.format("%.2f", descuento) + "\n"
        + "IVA: Q" + String.format("%.2f", iva) + "\n"
        + "Total: Q" + String.format("%.2f", total) + "\n"
        + "Forma de pago: " + formaPago;

    if (opcionPago == 1) {
        resumen +=
            "\nEfectivo recibido: Q"
            + String.format("%.2f", efectivoRecibido)
            + "\nCambio: Q" + String.format("%.2f", cambio);
    }

    JOptionPane.showMessageDialog(null, resumen);
} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(
        this,
        "Entrada no válida o cancelada. La venta no se completó.",
        "Error de entrada",
        JOptionPane.WARNING_MESSAGE
    );
}
    
    
    }//GEN-LAST:event_jButton1ActionPerformed

